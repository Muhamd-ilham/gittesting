// Trending Blog :: Sidebar
function trending_blog() {
    global $oketheme;
    if(!empty($oketheme['sidebar']['trending_blog']['act'])) {
        $args = array(
            'posts_per_page' => $oketheme['sidebar']['trending_blog']['count'],
            'meta_key'       => 'post_views_count',
            'orderby'        => 'meta_value_num',
            'order'          => 'DESC',  
            'ignore_sticky_posts' => true,
        );
        if ($oketheme['sidebar']['trending_blog']['period'] !== 'all') {
            $date_query = array(
                array(
                    'after'     => $oketheme['sidebar']['trending_blog']['period'],
                    'inclusive' => true,
                ),
            );
            $args['date_query'] = $date_query;
        }
        $the_query = new WP_Query($args);?>
        <div id="trending-blog"class="box-content" data-customize-partial-id="sidebar" data-helper-title="Post Populer" data-helper-tab="sidebar">
            <div class="_title">
                <h4><?=$oketheme['sidebar']['trending_blog']['title']?:__('Terpopuler','oketheme'); ?></h4>
            </div>
            <?php if ($the_query->have_posts()) {
                echo '<ol class="list">';
                $count = 0; // Counter untuk melacak iterasi
                while ($the_query->have_posts()):
                    $the_query->the_post();
                    if ($count === 0) {
                        // Postingan pertama menggunakan template berbeda
                        loop('regular');
                    } else {
                        // Postingan lainnya menggunakan template standar
                        loop('thumbnail');
                    }
                    $count++;
                endwhile;
                echo '</ol>';
                wp_reset_postdata(); 
            } else { ?>
                <p><?php _e('Maaf, saat ini belum tersedia post untuk ditampilkan.', 'oketheme'); ?></p>
            <?php } ?>
        </div>
    <?php }
}

