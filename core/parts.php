// Related @ Content (Baca Juga)
function related_content() {
    global $oketheme;
    if (!$oketheme['read_also_act']) return;

    $category_ids = wp_get_post_categories(get_the_ID());
    $tag_ids = wp_get_post_tags(get_the_ID(), array('fields' => 'ids'));

    if (empty($category_ids) && empty($tag_ids)) return;

    $related_posts = new WP_Query(array(
        'post_type'           => 'post',
        'posts_per_page'      => 2,
        'orderby'             => 'rand',
        'post__not_in'        => array(get_the_ID()),
        'ignore_sticky_posts' => true,
        'tax_query'           => array(
            'relation' => 'OR',
            !empty($category_ids) ? array(
                'taxonomy' => 'category',
                'field'    => 'term_id',
                'terms'    => $category_ids,
            ) : null,
            !empty($tag_ids) ? array(
                'taxonomy' => 'post_tag',
                'field'    => 'term_id',
                'terms'    => $tag_ids,
            ) : null,
        ),
    ));

    if (!$related_posts->have_posts()) return;

    echo '<div id="related-posts" style="display:none;">';

    while ($related_posts->have_posts()) {
        $related_posts->the_post();
        echo '<div class="related-content" data-customize-partial-id="single" data-helper-title="Baca Juga" data-helper-tab="single-post"><b>'.__('Baca juga', 'oketheme').': </b><a href="' . get_permalink() . '">' . get_the_title() . '</a></div>';
    }

    echo '</div>';
    wp_reset_postdata(); ?>
        <script>
            jQuery(document).ready(function ($) {
                var relatedPosts = $('#related-posts .related-content');
                var childDivs = $('.wrap-post._artikel').children();

                if (childDivs.length === 0 || relatedPosts.length === 0) return;

                if (childDivs.length < 6) {
                    relatedPosts.slice(1).remove();
                    var middleIndex = Math.floor(childDivs.length / 2);
                    relatedPosts.first().insertAfter(childDivs.eq(middleIndex - 1)).show();
                } else {
                    var firstIndex = Math.floor(childDivs.length / 5);
                    var secondIndex = Math.floor(4 * childDivs.length / 5);

                    relatedPosts.eq(0).insertAfter(childDivs.eq(firstIndex - 1)).show();
                    relatedPosts.eq(1).insertAfter(childDivs.eq(secondIndex - 1)).show();
                }

                // Hapus div kosong setelah pindah
                $('#related-posts').remove();
            });

        </script>
    <?php
}

// Related Blog
function related_blog() {
    global $oketheme;
    if (empty($oketheme['related_blog']['act'])) return;

    $category_ids = array();
    $tag_ids = array();

    // Mengambil ID kategori
    $categories = get_the_category();
    if (!empty($categories) && is_array($categories)) {
        foreach ($categories as $category) {
            $category_ids[] = $category->term_id;
        }
    }

    // Mengambil ID tag
    $tags = get_the_tags();
    if (!empty($tags) && is_array($tags)) {
        foreach ($tags as $tag) {
            $tag_ids[] = $tag->term_id;
        }
    }

    // Cek apakah ada kategori atau tag
    if (empty($category_ids) && empty($tag_ids)) return;

    // Membuat query untuk post terkait berdasarkan kategori ATAU tag
    $args = array(
        'post_type'             => 'post',
        'posts_per_page'        => 4,
        'post__not_in'          => array(get_the_ID()),
        'ignore_sticky_posts'   => true,
        'tax_query'             => array(
            'relation' => 'OR',
            !empty($category_ids) ? array(
                'taxonomy' => 'category',
                'field'    => 'term_id',
                'terms'    => $category_ids,
            ) : null,
            !empty($tag_ids) ? array(
                'taxonomy' => 'post_tag',
                'field'    => 'term_id',
                'terms'    => $tag_ids,
            ) : null,
        ),
    );

    // Hapus elemen null dari tax_query
    $args['tax_query'] = array_filter($args['tax_query']);

    $the_query = new WP_Query($args);
    if (!$the_query->have_posts()) return;
    ?>

    <div id="related-blog" class="box-content" data-customize-partial-id="single" data-helper-title="Post Terkait" data-helper-tab="single-post">
        <div class="_title">
            <h2><?=$oketheme['related_blog']['title']?:__('Post Terkait','oketheme'); ?></h2>
        </div>
        <div class="grid two-col">
            <?php while ($the_query->have_posts()): $the_query->the_post(); loop('thumbnail'); endwhile; ?>
        </div>
    </div>
    <?php
    wp_reset_postdata();
}

