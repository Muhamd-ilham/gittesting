function is_ads_active() {
    global $oketheme;
    foreach ($oketheme['ads_show'] as $page_type) {
        if (
            ($page_type === 'home' && is_home()) ||
            ($page_type === 'post' && is_single()) ||
            ($page_type === 'page' && is_page()) ||
            ($page_type === 'archive' && is_archive()) ||
            ($page_type === 'search' && is_search()) ||
            ($page_type === '404' && is_404()) ||
            ($page_type === 'attachment' && is_attachment())
        ) {
            return true;
        }
    }
    return false;
}

