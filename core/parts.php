// Theme Head
add_action( 'wp_head', 'theme_head');
function theme_head() {
    global $oketheme;

    // Favicon
    if($oketheme['fav_web']) {
        echo '<link href="'.$oketheme['fav_web'].'" type="image/x-icon" rel="icon" />';
    }

    // Dark Mode
    if ($oketheme['dark_mode']['act'] && ((isset($_COOKIE['warta_dark']) && $_COOKIE['warta_dark'] == '1') || (!isset($_COOKIE['warta_dark']) && $oketheme['dark_mode']['default']))) { ?>
        <link rel="stylesheet" type="text/css" href="<?php echo get_template_directory_uri(); ?>/assets/css/dark.css" id="darkmode-stylesheet" /> 
    <?php }

    // Responsive
    if ($oketheme['responsive_act']) { ?>
		<link rel="stylesheet" type="text/css" href="<?php echo get_template_directory_uri(); ?>/assets/css/responsive.css" media="all" />
		<meta name="viewport" content="width=device-width, initial-scale=1" />
	<?php } else { ?>
        <meta name="viewport" content="width=1092" />
        <style>
            body {min-width: 1092px}
            .banner-floating._side {display: none;}
        </style>
    <?php }

    // Font Family
	if ($oketheme['typography']['type'] == 'google') { ?>
		<link href="https://fonts.googleapis.com/css2?family=<?=$oketheme['typography']['font-family'];?>:wght@400;500;600;700&display=swap" rel="stylesheet">
	<?php } ?>

    <!-- CSS -->
    <style type="text/css">

        /* Root Custom */
        :root {
            --color1: <?=$oketheme['color1'];?>;
            --color2: <?=$oketheme['color2'];?>;
            <?=$oketheme['corner_style']=='flat'?'--bradius: 0;':'';?>
        }

        /* Posisi Sidebar */
        <?php if($oketheme['sidebar_lr']=='left') {
            echo '#content { flex-direction:row-reverse; }';
        } ?>
        <?php if(!empty($oketheme['htop']['feat_blog']['bg_act'])) { ?>
            #feat-blog._bg { 
                background: linear-gradient(<?=$oketheme['htop']['feat_blog']['bg']['background-gradient-direction'];?>, <?=$oketheme['htop']['feat_blog']['bg']['background-color'];?> 33%, <?=$oketheme['htop']['feat_blog']['bg']['background-gradient-color'];?>); 
            }
            <?php if(!empty($oketheme['htop']['feat_blog']['bg']['background-image']['url'])) { ?>
                #feat-blog._bg:before {
                    background-image: url('<?=$oketheme['htop']['feat_blog']['bg']['background-image']['url'];?>');
                }
            <?php }
        } ?>

        /* Custom CSS */
        <?=$oketheme['custom_css']?:'';?>

    </style>
    
    <!-- Header Code -->
    <?=$oketheme['header_code']?:'';?>

<?php }

