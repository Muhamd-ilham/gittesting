			} 
			// Youtube Video
			else if ($oketheme['popup_act'] == 'youtube' && $oketheme['popup_youtube']) { ?>
				<iframe width="600" height="320" src="https://www.youtube.com/embed/<?=get_yID($oketheme['popup_youtube']); ?>?autoplay=0&rel=0" frameborder="0" allowfullscreen></iframe>
			<?php } 
			// Tiktok
			else if ($oketheme['popup_act'] == 'tiktok' && $oketheme['popup_tiktok']) { ?>
				<?php $tik = json_decode(ocurl('https://www.tiktok.com/oembed?url=' . $oketheme['popup_tiktok']), true); echo $tik['html'];?>
			<?php } 
			// HTML
			else if ($oketheme['popup_act'] == 'html' && $oketheme['popup_html']) {
				echo $oketheme['popup_html']; ?>
			<?php } else {
                echo '<b>Perhatian:</b> Terjadi kesalahan, cek kembali pengaturan fitur Popup pada theme options.';
            } ?>
		</div>
	<?php }
}

// Flash Blog (Breaking News)
function flash_blog() {
    global $oketheme;
    if(!empty($oketheme['flash_blog']['act'])) {
        $args = array(
            'post_type' => 'post',
            'showposts' => 6,
            'ignore_sticky_posts' => true,
        );
        if (!empty($oketheme['flash_blog']['cat'])) {
            $args['cat'] = $oketheme['flash_blog']['cat'];
        } else {
            $args['orderby'] = 'rand';
        }
        $the_query = new WP_Query($args); 
        if(!$the_query->have_posts()) return the_current_day();
        ?>

        <div id="flash-blog" class="flexcon gap-10" <?=$oketheme['topsearch_act']?'':'style="width:100%"'?> data-customize-partial-id="header" data-helper-title="Breaking News" data-helper-tab="header">
            <?php if($oketheme['flash_blog']['title']) { ?>
                <div class="_title">
                    <?php echo $oketheme['flash_blog']['title']; ?>
                </div>
            <?php } ?>
            <div class="splide">
                <div class="splide__track">
                    <ul class="splide__list">
                        <?php while ($the_query->have_posts()):$the_query->the_post(); 
                            echo '<li class="splide__slide elipsis"><a title="'.get_the_title().'" href="'.get_the_permalink().'">'.get_the_title().'</a></li>';
                        endwhile;?>
                    </ul>
                </div>
            </div>
        </div>
        <?php wp_reset_postdata();
    } else {
        the_current_day();
    }
}

