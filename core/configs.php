// Convert to WebP
function convert_to_webp($metadata, $attachment_id) {
    global $oketheme;
    if(!$oketheme['convert_webp_act']) return $metadata;
    if (get_transient('convertwebp_status') !== '1') return $metadata;

    $upload_dir = wp_upload_dir();
    $base_dir = $upload_dir['basedir'];
    $file_path = $base_dir . '/' . $metadata['file'];
    $file_info = pathinfo($file_path);

    // Konversi file utama ke WebP
    $webp_main = $file_info['dirname'] . '/' . $file_info['filename'] . '.webp';

    if (convert_image_to_webp($file_path, $webp_main) && file_exists($webp_main)) {
        // Perbarui metadata agar menggunakan WebP
        $metadata['file'] = str_replace($file_info['basename'], $file_info['filename'] . '.webp', $metadata['file']);
        
        // Hapus file asli
        unlink($file_path);
        
        // Perbarui informasi file di database
        $webp_url = str_replace($upload_dir['basedir'], $upload_dir['baseurl'], $webp_main);
        wp_update_post([
            'ID' => $attachment_id,
            'guid' => $webp_url // Pastikan URL di database adalah WebP
        ]);
        
        // Perbarui meta file asli agar WordPress tidak mencari format lama
        update_post_meta($attachment_id, '_wp_attached_file', str_replace($upload_dir['basedir'] . '/', '', $metadata['file']));
    }

    // Konversi semua ukuran gambar
    foreach ($metadata['sizes'] as $size => $data) {
        $original_size_path = $file_info['dirname'] . '/' . $data['file'];
        $webp_size_path = preg_replace('/\.(jpg|jpeg|png|gif)$/i', '.webp', $original_size_path);

        if (convert_image_to_webp($original_size_path, $webp_size_path) && file_exists($webp_size_path)) {
            $metadata['sizes'][$size]['file'] = basename($webp_size_path);
            unlink($original_size_path);
        }
    }

    return $metadata;
}
add_filter('wp_generate_attachment_metadata', 'convert_to_webp', 10, 2);
function convert_image_to_webp($source, $destination) {
    if (!file_exists($source)) return false;

    $image_info = getimagesize($source);
    $mime = $image_info['mime'];

    switch ($mime) {
        case 'image/jpeg':
            $image = imagecreatefromjpeg($source);
            break;
        case 'image/png':
            $image = imagecreatefrompng($source);
            imagepalettetotruecolor($image);
            imagealphablending($image, false);
            imagesavealpha($image, true);
            break;
        default:
            return false;
    }

    if (isset($image)) {
        imagewebp($image, $destination, 80);
        imagedestroy($image);
        return file_exists($destination);
    }

    return false;
}

