        add_rewrite_rule('^' . $oketheme['custom_login']['slug'] . '/?$','wp-login.php?' . $oketheme['custom_login']['slug'] . '=1','top');

        // Kalau user sudah login dan buka wp-login.php/myadmin → redirect dashboard
        if ( is_user_logged_in() && $pagenow === 'wp-login.php' && !isset($_GET['action']) ) {
            wp_redirect( admin_url() );
            exit;
        }

        // Izinkan action=logout tetap berjalan normal
        if ( $pagenow === 'wp-login.php' && isset($_GET['action']) && $_GET['action'] === 'logout' ) {
            return;
        }

        // Kalau belum login dan akses wp-login.php langsung (GET) tanpa parameter → redirect ke homepage
        if (
            $pagenow === 'wp-login.php'
            && $_SERVER['REQUEST_METHOD'] === 'GET'
            && !isset($_GET[$oketheme['custom_login']['slug']])
            && !isset($_GET['action'])
        ) {
            wp_redirect( home_url() );
            exit;
        }

        if ( is_admin() && !is_user_logged_in() && !( defined('DOING_AJAX') && DOING_AJAX ) ) {
            wp_redirect( home_url() );
            exit;
        }
    }
});

