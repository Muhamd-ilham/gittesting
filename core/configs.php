// Get Youtube Video ID
function get_yID($video_url) {
    // Jika URL menggunakan format youtu.be
    if (strpos($video_url, 'youtu.be') !== false) {
        $id = substr($video_url, strrpos($video_url, '/') + 1);
    } 
    // Jika URL menggunakan format youtube.com/watch?v=
    elseif (strpos($video_url, 'youtube.com') !== false && strpos($video_url, 'v=') !== false) {
        $queryString = parse_url($video_url, PHP_URL_QUERY);
        parse_str($queryString, $params);
        $id = isset($params['v']) ? $params['v'] : '';
    } 
    // Jika URL tidak valid
    else {
        $id = '';
    }
    return $id;
}

