// Get Image Size
function get_wh_img($img_url) {
    // Inisialisasi cURL
    $ch = curl_init();
    curl_setopt($ch, CURLOPT_URL, $img_url);
    curl_setopt($ch, CURLOPT_RETURNTRANSFER, 1);
    curl_setopt($ch, CURLOPT_BINARYTRANSFER, 1);

    // Mendapatkan konten gambar
    $imageData = curl_exec($ch);
    curl_close($ch);

    // Mendapatkan ukuran gambar
    if ($imageData !== false) {
        $imageSize = getimagesizefromstring($imageData);
        if ($imageSize !== false) {
            $width = $imageSize[0];
            $height = $imageSize[1];
            return 'width="' . $width . '" height="' . $height . '"';
        }
    }
}

// Get Image URL by ID Attachment
function img_url($id, $size = 'full') {
    if (empty($id)) {
        return '';
    }
    $image_url = wp_get_attachment_image_src($id, $size);
    if (is_array($image_url) && !empty($image_url[0])) {
        return $image_url[0];
    } else {
        return '';
    }
}

// Menambahkan ALT text ke gambar
add_filter('post_thumbnail_html', function($html, $post_id, $post_thumbnail_id, $size, $attr) {
    global $oketheme;
    if (!$oketheme['auto_alt_act']) return $html;

    $post_title = esc_attr(get_the_title($post_id));
    $current_alt = get_post_meta($post_thumbnail_id, '_wp_attachment_image_alt', true);

    // Jika ALT sudah ada dan tidak kosong, biarkan
    if (!empty($current_alt)) return $html;

    // Tambahkan atau ganti ALT jika kosong
    if (preg_match('/alt\s*=\s*""/', $html)) {
        $html = preg_replace('/alt\s*=\s*""/', 'alt="' . $post_title . '"', $html);
    } elseif (strpos($html, 'alt=') === false) {
        $html = preg_replace('/<img(.*?)\/?>/i', '<img$1 alt="' . $post_title . '" />', $html);
    }

    return $html;
}, 10, 5);

