function lang_list() {
	$dir = get_template_directory().'/lang'; 
	if ($handle = opendir($dir)) {
		$value 	= array ();
		$text 	= array ();
		while (false !== ($file = readdir($handle))) {
			if ($file != "." && $file != ".." && strtolower(substr($file, strrpos($file, '.') + 1)) == 'php')  {
				$value[]	= basename($file, '.php');
				$text[]		= ucfirst(basename($file, '.php'));
			}
		}
		$lang	= array_combine($value,$text);
		return $lang;
		closedir($handle);
	}
}

