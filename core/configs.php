// Popular Tags
function the_popular_tags($period = 'all') {
    global $wpdb;
    $limit  = 15;
    $tags   = [];
    $today  = current_time('mysql');

    // Daftar periode yang tersedia
    $periods = [
        '7d'  => 7 * DAY_IN_SECONDS,
        '1m'  => 30 * DAY_IN_SECONDS,
        '3m'  => 90 * DAY_IN_SECONDS,
        '1y'  => 365 * DAY_IN_SECONDS,
        'all' => 0, // Sepanjang masa
    ];

    // Pastikan periode yang dipilih valid
    if (!isset($periods[$period])) {
        $period = '1m'; // Gunakan default 1 bulan jika periode tidak valid
    }

    // Jika bukan 'all', hitung tanggal mulai
    $start_date = $periods[$period] ? date('Y-m-d H:i:s', strtotime($today) - $periods[$period]) : null;

    // Query berdasarkan periode
    if ($start_date) {
        $query = $wpdb->prepare("
            SELECT terms.term_id, terms.name, terms.slug, COUNT(tr.object_id) AS tag_count
            FROM {$wpdb->term_taxonomy} AS tt
            INNER JOIN {$wpdb->terms} AS terms ON tt.term_id = terms.term_id
            INNER JOIN {$wpdb->term_relationships} AS tr ON tt.term_taxonomy_id = tr.term_taxonomy_id
            INNER JOIN {$wpdb->posts} AS posts ON tr.object_id = posts.ID
            WHERE tt.taxonomy = 'post_tag' 
                AND posts.post_status = 'publish'
                AND posts.post_date >= %s
            GROUP BY terms.term_id
            ORDER BY tag_count DESC
            LIMIT {$limit}
        ", $start_date);
    } else {
        // Query untuk sepanjang masa (tanpa filter tanggal)
        $query = "
            SELECT terms.term_id, terms.name, terms.slug, COUNT(tr.object_id) AS tag_count
            FROM {$wpdb->term_taxonomy} AS tt
            INNER JOIN {$wpdb->terms} AS terms ON tt.term_id = terms.term_id
            INNER JOIN {$wpdb->term_relationships} AS tr ON tt.term_taxonomy_id = tr.term_taxonomy_id
            WHERE tt.taxonomy = 'post_tag'
            GROUP BY terms.term_id
            ORDER BY tag_count DESC
            LIMIT {$limit}
        ";
    }

    $tags = $wpdb->get_results($query);

    // Output tags dalam format #hashtag link
    if (!empty($tags)) {
        echo '<div class="_content hscroll">';
        foreach ($tags as $tag) {
            $tag_link = get_tag_link($tag->term_id);
            echo '<a href="' . esc_url($tag_link) . '">#' . esc_html($tag->name) . '</a> ';
        }
        echo '</div>';
    } else {
        echo __('Maaf, tidak ditemukan tags pada periode waktu yang ditentukan.', 'oketheme');
    }
}

