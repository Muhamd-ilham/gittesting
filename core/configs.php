// Hour Post Time
function the_post_time() {
    $post_time = get_the_time('U'); // timestamp posting
    $current_time = current_time('timestamp');
    $time_diff = $current_time - $post_time;

    if ($time_diff < DAY_IN_SECONDS) {
        $hours_ago = floor($time_diff / HOUR_IN_SECONDS);
        if ($hours_ago == 0) {
            $minutes_ago = floor($time_diff / MINUTE_IN_SECONDS);
            echo $minutes_ago . ' ' . __('menit yang lalu', 'oketheme');
        } else {
            echo $hours_ago . ' ' . __('jam yang lalu', 'oketheme');
        }
    } else {
        // Paksa ambil nama hari & bulan dalam English
        $english_day   = gmdate('D', $post_time); // ex: Sun, Mon, Tue
        $english_month = gmdate('M', $post_time); // ex: Jan, Feb, Mar

        $days = array(
            'Sun' => __('Minggu', 'oketheme'),
            'Mon' => __('Senin', 'oketheme'),
            'Tue' => __('Selasa', 'oketheme'),
            'Wed' => __('Rabu', 'oketheme'),
            'Thu' => __('Kamis', 'oketheme'),
            'Fri' => __('Jumat', 'oketheme'),
            'Sat' => __('Sabtu', 'oketheme'),
        );

        $months = array(
            'Jan' => __('Jan', 'oketheme'),
            'Feb' => __('Feb', 'oketheme'),
            'Mar' => __('Mar', 'oketheme'),
            'Apr' => __('Apr', 'oketheme'),
            'May' => __('Mei', 'oketheme'),
            'Jun' => __('Jun', 'oketheme'),
            'Jul' => __('Jul', 'oketheme'),
            'Aug' => __('Agt', 'oketheme'),
            'Sep' => __('Sep', 'oketheme'),
            'Oct' => __('Okt', 'oketheme'),
            'Nov' => __('Nov', 'oketheme'),
            'Dec' => __('Des', 'oketheme'),
        );

        $day   = isset($days[$english_day]) ? $days[$english_day] : $english_day;
        $month = isset($months[$english_month]) ? $months[$english_month] : $english_month;

        // format akhir: "Rabu, 6 Nov 2025"
        echo $day . ', ' . gmdate('j', $post_time) . ' ' . $month . ' ' . gmdate('Y', $post_time);
    }
}

