// Configuration
function config_data() {
    return array(
        'opt_safe_mode'     => false,
        'opt_post_max_show' => 100,
        'opt_cat_max_show'  => 100,
        'opt_tag_max_show'  => 100,
        'opt_custom_mode'   => false,
        'opt_custom_fields' => array(),
        'php_default'       => '7.4',
        // 'php_required'      => array('7.2', '7.3', '7.4'),
        'php_required'      => array('8.2'),
    );
}

// Checking PHP & IonCube Loader
$php_version    = PHP_VERSION;
$required_php   = config_data()['php_required'];
$ioncube_loaded = function_exists('ioncube_loader_version');
$compatible_php = false;

// Jika php_required kosong → fallback minimal php_default
if (empty($required_php)) {
    $compatible_php = version_compare($php_version, config_data()['php_default'], '>=');
} else {
    foreach ($required_php as $ver) {
        if (version_compare($php_version, $ver, '>=') && version_compare($php_version, (float)$ver + 0.1, '<')) {
            $compatible_php = true;
            break;
        }
    }
}

// Jika tidak memenuhi syarat
if ( ! $compatible_php || ! $ioncube_loaded ) {

    if ( is_admin() && current_user_can('manage_options') ) {
        add_action('admin_notices', function() use ($php_version, $required_php, $ioncube_loaded, $compatible_php) {
            $required_text = !empty($required_php) ? implode('.x, ', $required_php) . '.x' : '>= ' . config_data()['php_default'];

            echo '<div class="notice notice-error"><p><strong style="color:red">Server Requirements Warning</strong><br>'
                . wp_get_theme()->Name . ' Theme belum dapat digunakan karena memerlukan <b style="color:green">PHP ' . $required_text . '</b> dan ekstensi <b style="color:green">IonCube Loader</b>.</p><p>';

            if ( ! $compatible_php ) {
                echo '<span class="dashicons dashicons-no-alt" style="color:red"></span> Server Anda menggunakan PHP ' . $php_version . '<br>';
            } else {
                echo '<span class="dashicons dashicons-yes" style="color:green"></span> Server Anda sudah menggunakan PHP ' . $php_version . '<br>';
                if ( ! $ioncube_loaded ) {
                echo '<span class="dashicons dashicons-no-alt" style="color:red"></span> Ekstensi IonCube Loader belum diaktifkan<br>';
            }
            }

            echo '</p><p>Silakan lakukan perubahan melalui control panel hosting/server Anda. Anda juga dapat menghubungi penyedia hosting untuk membantu melakukan perubahan tersebut.</p></div>';
        });
    }

    if ( ! is_admin() ) {
        add_action('template_redirect', function() {
            echo '<link rel="preconnect" href="https://fonts.gstatic.com">';
            echo '<link href="https://fonts.googleapis.com/css2?family=Roboto:wght@400;700&display=swap" rel="stylesheet">';
            echo '
            <div style="text-align:center;max-width:700px;margin:40px auto;font-family:Roboto;font-size: 16px;">
                <h1 style="margin:0;font-weight:700">WEBSITE BELUM SIAP!</h1>
                <p><img src="'. get_template_directory_uri() .'/inc/codestar/assets/images/maintenance.gif"></p>
                <p>Maaf, website kami belum siap saat ini. Silahkan kunjungi lagi nanti, terima kasih :-)</p>
                <p style="font-size:12px">Jika Anda adalah admin website ini, silahkan login <a href="'. get_bloginfo('url') .'/wp-admin/themes.php"><u>disini</u></a></p>
            </div>';
            exit;
        });
    }

} else {
    ob_start();
    
    // Semua syarat terpenuhi, load required file
    require_once( dirname( __FILE__ ) . '/core/en/locked.php');
    require_once( dirname( __FILE__ ) . '/core/configs.php');
    require_once( dirname( __FILE__ ) . '/core/parts.php');

    if (isset($_GET['activated']) && is_admin()) {
        wp_safe_redirect(admin_url('admin.php?page=verifikasi-oketheme'));
        exit;
    }
}
